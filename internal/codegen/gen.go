// baseType 返回字段的 Go 基础类型（不含数组/可选修饰）。
func (g *gen) baseType(f Field) (string, error) {
	switch f.FieldType {
	case "scalar":
		switch f.ScalarType {
		case "int32":
			return "int32", nil
		case "int64":
			if f.DataType == "uin" {
				if t, ok := idTypes[f.Name]; ok {
					return t, nil
				}
				return "Uin", nil
			}
			if t, ok := seqTypes[f.Name]; ok {
				return t, nil
			}
			return "int64", nil
		case "bool":
			return "bool", nil
		case "string":
			return "string", nil
		default:
			return "", fmt.Errorf("字段 %q: 未知标量类型 %q", f.Name, f.ScalarType)
		}
	case "enum":
		spec, ok := enumByField[f.Name]
		if !ok {
			return "", fmt.Errorf("字段 %q: 枚举未命名", f.Name)
		}
		return spec.TypeName, nil
	case "ref":
		if _, ok := g.ir.FindStruct(f.RefStructName); !ok {
			return "", fmt.Errorf("字段 %q: 未知引用 %q", f.Name, f.RefStructName)
		}
		return f.RefStructName, nil
	default:
		return "", fmt.Errorf("字段 %q: 未知字段类型 %q", f.Name, f.FieldType)
	}
}

// isUnionRef 报告引用目标是否是联合类型（接口）。
func (g *gen) isUnionRef(name string) bool {
	s, ok := g.ir.FindStruct(name)
	return ok && s.StructType == "union"
}

// goType 返回字段完整的 Go 类型。
func (g *gen) goType(f Field) (string, error) {
	base, err := g.baseType(f)
	if err != nil {
		return "", err
	}
	if f.IsArray {
		switch base {
		case "IncomingSegment":
			return "IncomingSegments", nil
		case "OutgoingSegment":
			return "OutgoingSegments", nil
		case "IncomingMessage":
			return "[]IncomingMessage", nil
		case "GroupNotification":
			return "[]GroupNotification", nil
		}
		return "[]" + base, nil
	}
	if f.IsOptional && !g.isUnionRef(base) {
		return "*" + base, nil
	}
	return base, nil
}

// unionFields 返回字段中引用联合类型（接口）的项。
//
// 这些字段无法直接交给 encoding/json 填充（接口没有具体类型），
// 需要在包含它们的结构体上生成自定义 UnmarshalJSON。
func (g *gen) unionFields(fields []Field) []Field {
	var out []Field
	for _, f := range fields {
		if f.FieldType == "ref" && g.isUnionRef(f.RefStructName) {
			out = append(out, f)
		}
	}
	return out
}

// fieldSpec 是生成结构体字段所需的全部信息。
type fieldSpec struct {
	name  string
	typ   string
	tag   string
	doc   []string
	since string
}

// fieldSpecs 把 IR 字段转成 Go 字段描述。
func (g *gen) fieldSpecs(fields []Field) ([]fieldSpec, error) {
	out := make([]fieldSpec, 0, len(fields))
	for _, f := range fields {
		typ, err := g.goType(f)
		if err != nil {
			return nil, err
		}
		out = append(out, fieldSpec{
			name:  pascal(f.Name),
			typ:   typ,
			tag:   jsonTag(f),
			doc:   docLines(f.Description),
			since: f.Since,
		})
	}
	return out, nil
}

// jsonTag 生成结构体标签。
//
// 规则（对应协议兼容性契约 C2）：
//   - 可选字段：指针 + omitempty，避免把 Go 零值当成显式值上送；
//   - 带默认值字段：值类型 + omitempty，让协议端应用自己的默认值；
//   - 其余字段：固定序列化。
func jsonTag(f Field) string {
	name := f.Name
	if f.IsOptional || f.HasDefault() {
		return name + ",omitempty"
	}
	return name
}

// docLines 把描述整理成注释行。
func docLines(s string) []string {
	s = strings.TrimSpace(s)
	if s == "" {
		return nil
	}
	s = strings.ReplaceAll(s, "\r", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	for strings.Contains(s, "  ") {
		s = strings.ReplaceAll(s, "  ", " ")
	}
	return []string{s}
}

func cleanText(s string) string {
	lines := docLines(s)
	if len(lines) == 0 {
		return ""
	}
	return lines[0]
}

// emitStruct 输出一个结构体。
func (g *gen) emitStruct(w *writer, name, desc string, specs []fieldSpec) {
	if desc != "" {
		w.p("// %s %s。", name, cleanText(desc))
	} else {
		w.p("// %s 。", name)
	}
	if len(specs) == 0 {
		w.p("type %s struct{}", name)
		w.p("")
		return
	}
	w.p("type %s struct {", name)
	for _, s := range specs {
		for _, d := range s.doc {
			w.p("\t// %s", d)
		}
		if s.since != "" {
			w.p("\t// 自 Milky %s 起提供。", s.since)
		}
		if s.tag == "" {
			w.p("\t%s %s", s.name, s.typ)
		} else {
			w.p("\t%s %s `json:%q`", s.name, s.typ, s.tag)
		}
	}
	w.p("}")
	w.p("")
}

// emitEnumType 输出一个字符串枚举（含 String / Valid）。
func (g *gen) emitEnumType(w *writer, typeName, desc, constPrefix string, values []string) {
	if g.emittedEnums[typeName] {
		return
	}
	g.emittedEnums[typeName] = true

	w.p("// %s %s。", typeName, desc)
	w.p("type %s string", typeName)
	w.p("")
	w.p("const (")
	for _, v := range values {
		cn := constPrefix + pascal(v)
		w.p("\t// %s 对应协议取值 %q。", cn, v)
		w.p("\t%s %s = %q", cn, typeName, v)
	}
	w.p(")")
	w.p("")
	w.p("// String 返回协议原始取值。")
	w.p("func (v %s) String() string { return string(v) }", typeName)
	w.p("")
	w.p("// Valid 报告 v 是否为协议定义的取值。")
	w.p("func (v %s) Valid() bool {", typeName)
	w.p("\tswitch v {")
	consts := make([]string, 0, len(values))
	for _, v := range values {
		consts = append(consts, constPrefix+pascal(v))
	}
	w.p("\tcase %s:", strings.Join(consts, ", "))
	w.p("\t\treturn true")
	w.p("\t}")
	w.p("\treturn false")
	w.p("}")
	w.p("")
}
